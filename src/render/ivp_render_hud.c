/* ── Push helper ───────────────────────────────────────────────────────── */

static void push_hud_line(ivp_renderer_t *r,
                          float x0, float y0, float x1, float y1,
                          const float col[3])
{
    hud_vertex_t *v = (hud_vertex_t *)ivp_gpu_stream_push(&r->stream_2d, 2);
    if (!v) return;
    v[0].pos[0] = x0; v[0].pos[1] = y0;
    memcpy(v[0].col, col, 3 * sizeof(float));
    v[1].pos[0] = x1; v[1].pos[1] = y1;
    memcpy(v[1].col, col, 3 * sizeof(float));
}

/* ── Filled rectangles ─────────────────────────────────────────────────── */

typedef struct rect_vertex {
    float pos[2];
    float col[4];
} rect_vertex_t;

static void push_rect_layer(ivp_renderer_t *r, int layer, float x, float y, float w,
                            float h, const float col[3], float alpha)
{
    rect_vertex_t *v = (rect_vertex_t *)ivp_gpu_stream_push(&r->stream_rect[layer], 6);
    if (!v) return;
    const float xs[6] = { x, x + w, x, x + w, x + w, x };
    const float ys[6] = { y, y,     y + h, y,   y + h, y + h };
    for (int i = 0; i < 6; i++) {
        v[i].pos[0] = xs[i];
        v[i].pos[1] = ys[i];
        v[i].col[0] = col[0];
        v[i].col[1] = col[1];
        v[i].col[2] = col[2];
        v[i].col[3] = alpha;
    }
}

static void push_rect(ivp_renderer_t *r, float x, float y, float w, float h,
                      const float col[3], float alpha)
{
    push_rect_layer(r, IVP_RECT_FRONT, x, y, w, h, col, alpha);
}

void ivp_render_draw_rect(ivp_renderer_t *r, float x, float y, float w, float h,
                          const float color[3], float alpha)
{
    push_rect(r, x, y, w, h, color, alpha);
}

void ivp_render_draw_panel(ivp_renderer_t *r, float x, float y, float w, float h,
                           const float color[3], float alpha)
{
    push_rect_layer(r, IVP_RECT_PANEL, x, y, w, h, color, alpha);
}

void ivp_render_set_backdrop(ivp_renderer_t *r, const float top[3], const float bottom[3])
{
    if (!top || !bottom) { r->backdrop_on = false; return; }
    memcpy(r->backdrop_top, top, sizeof(r->backdrop_top));
    memcpy(r->backdrop_bottom, bottom, sizeof(r->backdrop_bottom));
    r->backdrop_on = true;
}

void ivp_hud_push_backdrop(ivp_renderer_t *r)
{
    rect_vertex_t *v = (rect_vertex_t *)ivp_gpu_stream_push(&r->stream_rect[IVP_RECT_BACKDROP], 6);
    if (!v) return;
    const float w = (float)r->width, h = (float)r->height;
    const float xs[6] = { 0, w, 0, w, w, 0 };
    const float ys[6] = { 0, 0, h, 0, h, h };
    const int bottom[6] = { 0, 0, 1, 0, 1, 1 };
    for (int i = 0; i < 6; i++) {
        const float *c = bottom[i] ? r->backdrop_bottom : r->backdrop_top;
        v[i].pos[0] = xs[i];  v[i].pos[1] = ys[i];
        v[i].col[0] = c[0];   v[i].col[1] = c[1];   v[i].col[2] = c[2];   v[i].col[3] = 1.0f;
    }
}

/* ── Text drawing ──────────────────────────────────────────────────────── */

void ivp_render_draw_text_scaled(ivp_renderer_t *r,
                                 float x, float y,
                                 const char *text,
                                 const float color[3],
                                 int scale)
{
    if (scale <= 0) scale = r->hud_font_scale;
    float cx = x, cy = y;
    float sc = (float)scale;

    for (const char *p = text; *p; p++) {
        if (*p == '\n') { cx = x; cy += (IVP_RENDER_HUD_FONT_H + 1) * sc; continue; }
        int ch = (int)(unsigned char)*p;
        if (ch < FONT_FIRST || ch > FONT_LAST) { cx += (IVP_RENDER_HUD_FONT_W + 1)*sc; continue; }
        const unsigned char *g = ivp_hud_font_data[ch - FONT_FIRST];
        for (int row = 0; row < IVP_RENDER_HUD_FONT_H; row++) {
            unsigned char bits = g[row];
            /* one rectangle per horizontal run of lit pixels */
            int col = 0;
            while (col < IVP_RENDER_HUD_FONT_W) {
                if (!(bits & (1 << (IVP_RENDER_HUD_FONT_W - 1 - col)))) { col++; continue; }
                int run = 1;
                while (col + run < IVP_RENDER_HUD_FONT_W &&
                       (bits & (1 << (IVP_RENDER_HUD_FONT_W - 1 - (col + run))))) run++;
                push_rect(r, cx + (float)col * sc, cy + (float)row * sc,
                          (float)run * sc, sc, color, 1.0f);
                col += run;
            }
        }
        cx += (IVP_RENDER_HUD_FONT_W + 1) * sc;
    }
}

void ivp_render_draw_text(ivp_renderer_t *r,
                          float x, float y,
                          const char *text,
                          const float color[3])
{
    ivp_render_draw_text_scaled(r, x, y, text, color, r->hud_font_scale);
}

void ivp_render_draw_text_aligned(ivp_renderer_t *r,
                                  float x, float y,
                                  const char *text,
                                  const float color[3],
                                  ivp_text_align_t align)
{
    if (align == IVP_TEXT_ALIGN_CENTER) {
        float w = ivp_render_text_width(text, r->hud_font_scale);
        x -= w * 0.5f;
    } else if (align == IVP_TEXT_ALIGN_RIGHT) {
        float w = ivp_render_text_width(text, r->hud_font_scale);
        x -= w;
    }
    ivp_render_draw_text(r, x, y, text, color);
}

void ivp_render_draw_text_fmt(ivp_renderer_t *r,
                              float x, float y,
                              const float color[3],
                              const char *fmt, ...)
{
    char buf[256];
    va_list args;
    va_start(args, fmt);
    vsnprintf(buf, sizeof(buf), fmt, args);
    va_end(args);
    ivp_render_draw_text(r, x, y, buf, color);
}

/* ── Text measurement ──────────────────────────────────────────────────── */

float ivp_render_text_width(const char *text, int scale)
{
    float sc = (float)scale;
    int count = 0;
    for (const char *p = text; *p && *p != '\n'; p++)
        count++;
    return (float)count * (IVP_RENDER_HUD_FONT_W + 1) * sc;
}

float ivp_render_line_height(int scale)
{
    return (IVP_RENDER_HUD_FONT_H + 1) * (float)scale;
}